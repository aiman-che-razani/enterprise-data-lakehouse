-- Idempotent. Run via SnowSQL or Flyway Snowflake plugin.

-- Warehouse sizing: use MEDIUM for initial load, resize in prod
CREATE WAREHOUSE IF NOT EXISTS RETAILNEXUS_LOAD_WH
    WITH WAREHOUSE_SIZE = 'MEDIUM'
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Warehouse used for Gold layer ETL loads';

CREATE DATABASE IF NOT EXISTS RETAILNEXUS;
CREATE SCHEMA IF NOT EXISTS RETAILNEXUS.GOLD;

-- Roles
CREATE ROLE IF NOT EXISTS RETAILNEXUS_ANALYST;
CREATE ROLE IF NOT EXISTS RETAILNEXUS_ENGINEER;

GRANT USAGE ON DATABASE RETAILNEXUS TO ROLE RETAILNEXUS_ANALYST;
GRANT USAGE ON SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ANALYST;

GRANT ALL PRIVILEGES ON DATABASE RETAILNEXUS TO ROLE RETAILNEXUS_ENGINEER;
GRANT ALL PRIVILEGES ON SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ENGINEER;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ENGINEER;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA RETAILNEXUS.GOLD TO ROLE RETAILNEXUS_ENGINEER;

